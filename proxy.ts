import {
  NextRequest,
  NextResponse,
} from "next/server";

import outputs from "./amplify_outputs.json";

/*
 * AWS origins are derived from the current Amplify environment.
 *
 * This is important because sandbox resources such as AppSync APIs
 * and S3 buckets may receive new identifiers after a sandbox is
 * recreated.
 *
 * We intentionally allow only the exact origins required by the
 * current environment instead of broad patterns such as
 * https://*.amazonaws.com.
 */
const APPSYNC_ORIGIN =
  new URL(
    outputs.data.url,
  ).origin;

const AUTH_REGION =
  outputs.auth.aws_region;

const STORAGE_REGION =
  outputs.storage.aws_region;

const COGNITO_IDP_ORIGIN =
  `https://cognito-idp.${AUTH_REGION}.amazonaws.com`;

const COGNITO_IDENTITY_ORIGIN =
  `https://cognito-identity.${AUTH_REGION}.amazonaws.com`;

const S3_ORIGIN =
  `https://${outputs.storage.bucket_name}.s3.${STORAGE_REGION}.amazonaws.com`;

function createContentSecurityPolicy(
  nonce: string,
): string {
  const isDevelopment =
    process.env.NODE_ENV ===
    "development";

  const directives = [
    /*
     * Block every resource type by default unless explicitly
     * allowed by a more specific directive below.
     */
    "default-src 'self'",

    /*
     * Only scripts generated by this Next.js request and carrying
     * the correct nonce may execute.
     *
     * unsafe-eval is required only by the development tooling.
     */
    [
      "script-src",
      "'self'",
      `'nonce-${nonce}'`,
      "'strict-dynamic'",
      ...(isDevelopment
        ? [
            "'unsafe-eval'",
          ]
        : []),
    ].join(" "),

    /*
     * Next.js can attach the request nonce to generated <style>
     * elements in production.
     *
     * Development requires unsafe-inline because the development
     * tooling injects styles dynamically.
     */
    [
      "style-src",
      "'self'",
      ...(isDevelopment
        ? [
            "'unsafe-inline'",
          ]
        : [
            `'nonce-${nonce}'`,
          ]),
    ].join(" "),

    /*
     * React components and UI libraries may legitimately use
     * inline style="" attributes.
     *
     * This does not permit inline JavaScript execution.
     */
    "style-src-attr 'unsafe-inline'",

    /*
     * Network destinations available to browser JavaScript.
     *
     * AWS service origins are intentionally scoped to the current
     * Amplify environment.
     */
    [
      "connect-src",
      "'self'",
      APPSYNC_ORIGIN,
      COGNITO_IDP_ORIGIN,
      COGNITO_IDENTITY_ORIGIN,
      S3_ORIGIN,
      ...(isDevelopment
        ? [
            "ws://localhost:*",
            "ws://127.0.0.1:*",
          ]
        : []),
    ].join(" "),

    /*
     * Images may originate from the application itself, generated
     * blob/data URLs, or the current Amplify Storage bucket.
     */
    [
      "img-src",
      "'self'",
      "data:",
      "blob:",
      S3_ORIGIN,
    ].join(" "),

    /*
     * Premium videos may be served from short-lived S3 URLs.
     */
    [
      "media-src",
      "'self'",
      "blob:",
      S3_ORIGIN,
    ].join(" "),

    "font-src 'self' data:",

    "worker-src 'self' blob:",

    /*
     * Do not allow plugins such as Flash or embedded object content.
     */
    "object-src 'none'",

    /*
     * Prevent an attacker from changing the meaning of relative
     * application URLs using a malicious <base> element.
     */
    "base-uri 'self'",

    /*
     * HTML forms may submit only back to this application.
     */
    "form-action 'self'",

    /*
     * The application currently does not embed third-party frames.
     */
    "frame-src 'none'",

    /*
     * Prevent this application from being embedded by another site.
     */
    "frame-ancestors 'none'",

    /*
     * Inline event handlers such as onclick="" are forbidden.
     */
    "script-src-attr 'none'",

    "manifest-src 'self'",

    /*
     * Production traffic must use HTTPS.
     *
     * Do not enable this during local HTTP development.
     */
    ...(isDevelopment
      ? []
      : [
          "upgrade-insecure-requests",
        ]),
  ];

  return directives
    .map(
      (directive) =>
        `${directive};`,
    )
    .join(" ");
}

export function proxy(
  request: NextRequest,
) {
  /*
   * Generate a new unpredictable nonce for every HTTP request.
   *
   * A stored or reflected XSS payload cannot know this nonce in
   * advance and therefore cannot simply inject an executable script.
   */
  const nonce =
    Buffer.from(
      crypto.randomUUID(),
    ).toString(
      "base64",
    );

  const contentSecurityPolicy =
    createContentSecurityPolicy(
      nonce,
    );

  const requestHeaders =
    new Headers(
      request.headers,
    );

  /*
   * Next.js reads the nonce from the incoming request headers and
   * can attach it to framework-generated scripts and styles.
   */
  requestHeaders.set(
    "x-nonce",
    nonce,
  );

  /*
   * Pass the CSP through the request as well because Next.js needs
   * access to it while rendering the response.
   *
   * This is an enforced CSP, not Report-Only.
   */
  requestHeaders.set(
    "Content-Security-Policy",
    contentSecurityPolicy,
  );

  const response =
    NextResponse.next({
      request: {
        headers:
          requestHeaders,
      },
    });

  /*
   * The browser enforces the CSP received in the response.
   */
  response.headers.set(
    "Content-Security-Policy",
    contentSecurityPolicy,
  );

  return response;
}

export const config = {
  matcher: [
    {
      source:
        "/((?!api|_next/static|_next/image|favicon.ico|icon.png).*)",

      /*
       * Skip speculative Next.js prefetch requests because they do
       * not need a separately generated CSP nonce.
       */
      missing: [
        {
          type: "header",
          key: "next-router-prefetch",
        },
        {
          type: "header",
          key: "purpose",
          value: "prefetch",
        },
      ],
    },
  ],
};