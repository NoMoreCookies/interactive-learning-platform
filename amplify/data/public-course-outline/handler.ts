export const handler:
  Schema["getPublishedCourseOutline"]["functionHandler"] =
  async (event) => withResolverBudget(12_000, async () => {
    const courseTableName =
      process.env
        .COURSE_TABLE_NAME;

    const moduleTableName =
      process.env
        .MODULE_TABLE_NAME;

    const lessonTableName =
      process.env
        .LESSON_TABLE_NAME;

    const courseSlugIndexName =
      process.env
        .COURSE_SLUG_INDEX_NAME;

    const moduleCourseIndexName =
      process.env
        .MODULE_COURSE_INDEX_NAME;

    const lessonModuleIndexName =
      process.env
        .LESSON_MODULE_INDEX_NAME;

    if (
      !courseTableName ||
      !moduleTableName ||
      !lessonTableName ||
      !courseSlugIndexName ||
      !moduleCourseIndexName ||
      !lessonModuleIndexName
    ) {
      console.error(
        "Public course outline DynamoDB configuration is incomplete.",
      );

      throw new Error(
        "Nie udało się pobrać struktury kursu.",
      );
    }

    const normalizedSlug =
      event.arguments.slug.trim();

    /*
     * Slug comes from a public caller.
     *
     * Empty or unreasonably long values are rejected before they
     * reach DynamoDB. We intentionally do not impose a restrictive
     * character regex here so existing valid slug conventions are
     * not accidentally broken.
     */
    if (
      !normalizedSlug ||
      normalizedSlug.length >
        MAX_SLUG_LENGTH
    ) {
      return null;
    }

    try {
      /*
       * Query only the GSI partition for the requested slug instead
       * of scanning the entire Course table.
       */
      const courseItems =
        await queryPublishedCourseBySlug(
          courseTableName,
          courseSlugIndexName,
          normalizedSlug,
        );

      if (
        courseItems.length === 0
      ) {
        return null;
      }

      /*
       * A DynamoDB GSI does not enforce uniqueness.
       *
       * Routing would become ambiguous if multiple published courses
       * shared the same slug, so we fail closed instead of choosing
       * an arbitrary record.
       */
      if (
        courseItems.length > 1
      ) {
        console.error(
          "Multiple published courses use the same slug.",
        );

        throw new Error(
          "Nie udało się jednoznacznie ustalić kursu.",
        );
      }

      const courseItem =
        courseItems[0];

      const courseId =
        getRequiredString(
          courseItem,
          "id",
        );

      /*
       * Query only the Module GSI partition belonging to this course.
       */
      const moduleItems =
        await queryPublishedModules(
          moduleTableName,
          moduleCourseIndexName,
          courseId,
        );

      moduleItems.sort(
        (
          firstModule,
          secondModule,
        ) =>
          getRequiredInteger(
            firstModule,
            "order",
          ) -
          getRequiredInteger(
            secondModule,
            "order",
          ),
      );

      const modules = [];

      /*
       * Each module is queried independently through the existing
       * moduleId relationship index.
       *
       * This is a deliberate bounded N+1 trade-off. It avoids a Scan
       * of every Lesson on the platform without denormalizing
       * courseId into Lesson.
       *
       * Queries are performed sequentially to avoid producing an
       * unnecessary DynamoDB request burst.
       */
      for (
        const moduleItem of
        moduleItems
      ) {
        const moduleId =
          getRequiredString(
            moduleItem,
            "id",
          );

        const moduleLessons =
          await queryPublishedLessonsByModule(
            lessonTableName,
            lessonModuleIndexName,
            moduleId,
          );

        moduleLessons.sort(
          (
            firstLesson,
            secondLesson,
          ) =>
            getRequiredInteger(
              firstLesson,
              "order",
            ) -
            getRequiredInteger(
              secondLesson,
              "order",
            ),
        );

        modules.push({
          id:
            moduleId,

          title:
            getRequiredString(
              moduleItem,
              "title",
            ),

          slug:
            getRequiredString(
              moduleItem,
              "slug",
            ),

          description:
            getOptionalString(
              moduleItem,
              "description",
            ),

          order:
            getRequiredInteger(
              moduleItem,
              "order",
            ),

          lessons:
            moduleLessons.map(
              (
                lessonItem,
              ) => ({
                id:
                  getRequiredString(
                    lessonItem,
                    "id",
                  ),

                title:
                  getRequiredString(
                    lessonItem,
                    "title",
                  ),

                slug:
                  getRequiredString(
                    lessonItem,
                    "slug",
                  ),

                description:
                  getOptionalString(
                    lessonItem,
                    "description",
                  ),

                durationMinutes:
                  getOptionalInteger(
                    lessonItem,
                    "durationMinutes",
                  ),

                order:
                  getRequiredInteger(
                    lessonItem,
                    "order",
                  ),
              }),
            ),
        });
      }

      return {
        id:
          courseId,

        title:
          getRequiredString(
            courseItem,
            "title",
          ),

        slug:
          getRequiredString(
            courseItem,
            "slug",
          ),

        description:
          getOptionalString(
            courseItem,
            "description",
          ),

        subject:
          getOptionalString(
            courseItem,
            "subject",
          ),

        level:
          getOptionalString(
            courseItem,
            "level",
          ),

        thumbnailPath:
          getOptionalString(
            courseItem,
            "thumbnailPath",
          ),

        order:
          getRequiredInteger(
            courseItem,
            "order",
          ),

        modules,
      };
    } catch (error) {
      console.error(
        "Failed to load public course outline.",
        {
          errorName:
            error instanceof Error
              ? error.name
              : "UnknownError",
        },
      );

      throw new Error(
        "Nie udało się pobrać struktury kursu.",
      );
    }
  });
