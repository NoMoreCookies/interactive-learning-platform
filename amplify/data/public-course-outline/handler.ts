import { boundedAwsOptions, budgetedClient, withResolverBudget } from "../../shared/resolver-budget";
import {
  DynamoDBClient,
  QueryCommand,
  type AttributeValue,
} from "@aws-sdk/client-dynamodb";

import type {
  Schema,
} from "../resource";

const dynamoDb =
  budgetedClient(new DynamoDBClient(boundedAwsOptions));

const MAX_SLUG_LENGTH = 200;

type DynamoDbItem =
  Record<string, AttributeValue>;

function getRequiredString(
  item: DynamoDbItem,
  fieldName: string,
): string {
  const value =
    item[fieldName];

  if (
    !value ||
    !("S" in value) ||
    typeof value.S !== "string"
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  return value.S;
}

function getOptionalString(
  item: DynamoDbItem,
  fieldName: string,
): string | null {
  const value =
    item[fieldName];

  if (!value) {
    return null;
  }

  if (
    !("S" in value) ||
    typeof value.S !== "string"
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  return value.S;
}

function getRequiredInteger(
  item: DynamoDbItem,
  fieldName: string,
): number {
  const value =
    item[fieldName];

  if (
    !value ||
    !("N" in value) ||
    typeof value.N !== "string"
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  const parsedValue =
    Number(value.N);

  if (
    !Number.isSafeInteger(
      parsedValue,
    )
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  return parsedValue;
}

function getOptionalInteger(
  item: DynamoDbItem,
  fieldName: string,
): number | null {
  const value =
    item[fieldName];

  if (!value) {
    return null;
  }

  if (
    !("N" in value) ||
    typeof value.N !== "string"
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  const parsedValue =
    Number(value.N);

  if (
    !Number.isSafeInteger(
      parsedValue,
    )
  ) {
    throw new Error(
      `Invalid ${fieldName} value.`,
    );
  }

  return parsedValue;
}

/*
 * Queries only the partition belonging to one slug.
 *
 * published remains a backend-controlled filter. The caller cannot
 * request unpublished courses.
 */
async function queryPublishedCourseBySlug(
  tableName: string,
  indexName: string,
  slug: string,
): Promise<DynamoDbItem[]> {
  const items:
    DynamoDbItem[] = [];

  let exclusiveStartKey:
    | Record<
        string,
        AttributeValue
      >
    | undefined;

  do {
    const result =
      await dynamoDb.send(
        new QueryCommand({
          TableName:
            tableName,

          IndexName:
            indexName,

          ExclusiveStartKey:
            exclusiveStartKey,

          KeyConditionExpression:
            "#slug = :slug",

          FilterExpression:
            "#published = :published",

          ProjectionExpression: [
            "#id",
            "#title",
            "#slug",
            "#description",
            "#subject",
            "#level",
            "#thumbnailPath",
            "#order",
          ].join(", "),

          ExpressionAttributeNames: {
            "#id":
              "id",

            "#title":
              "title",

            "#slug":
              "slug",

            "#description":
              "description",

            "#subject":
              "subject",

            "#level":
              "level",

            "#thumbnailPath":
              "thumbnailPath",

            "#order":
              "order",

            "#published":
              "published",
          },

          ExpressionAttributeValues: {
            ":slug": {
              S: slug,
            },

            ":published": {
              BOOL: true,
            },
          },
        }),
      );

    items.push(
      ...(result.Items ?? []),
    );

    exclusiveStartKey =
      result.LastEvaluatedKey;
  } while (
    exclusiveStartKey
  );

  return items;
}

