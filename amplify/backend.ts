/*
 * Stripe webhook HTTP API.
 *
 * This route must be publicly reachable because Stripe cannot
 * authenticate with our Cognito User Pool.
 *
 * Security is provided by Stripe's cryptographic webhook
 * signature, not by browser/user authentication.
 */
const stripeWebhookApiStack =
  backend.createStack(
    "stripe-webhook-api",
  );

const stripeWebhookIntegration =
  new HttpLambdaIntegration(
    "StripeWebhookIntegration",
    backend
      .stripeWebhook
      .resources
      .lambda,
  );

const stripeWebhookApi =
  new HttpApi(
    stripeWebhookApiStack,
    "StripeWebhookHttpApi",
    {
      apiName:
        "poprostumatma-stripe-webhook",

      createDefaultStage:
        true,
    },
  );

stripeWebhookApi.addRoutes({
  path:
    "/stripe/webhook",

  methods: [
    HttpMethod.POST,
  ],

  integration:
    stripeWebhookIntegration,
});

/*
 * Stripe webhook abuse protection.
 *
 * API Gateway throttling happens before Lambda invocation, reducing
 * the blast radius of unauthenticated request floods.
 */
const stripeWebhookDefaultStage =
  stripeWebhookApi
    .defaultStage;

if (
  !stripeWebhookDefaultStage
) {
  throw new Error(
    "Stripe webhook default stage was not created.",
  );
}

const stripeWebhookCfnStage =
  stripeWebhookDefaultStage
    .node
    .defaultChild as CfnStage;

stripeWebhookCfnStage.addPropertyOverride(
  "DefaultRouteSettings.ThrottlingRateLimit",
  10,
);

stripeWebhookCfnStage.addPropertyOverride(
  "DefaultRouteSettings.ThrottlingBurstLimit",
  20,
);

/*
 * Infrastructure-only output used to configure the Stripe webhook
 * endpoint.
 *
 * The URL is not a secret.
 */
new CfnOutput(
  stripeWebhookApiStack,
  "StripeWebhookEndpoint",
  {
    value:
      `${stripeWebhookApi.apiEndpoint}/stripe/webhook`,
  },
);

