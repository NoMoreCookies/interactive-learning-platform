const billingStack =
  backend.createStack(
    "billing",
  );

/*
 * Maps one Cognito user to one Stripe Customer.
 *
 * Primary access pattern:
 * userId -> Stripe Customer
 *
 * Reverse access pattern:
 * stripeCustomerId -> userId
 */
const billingCustomerTable =
  new Table(
    billingStack,
    "BillingCustomerTable",
    {
      partitionKey: {
        name:
          "userId",

        type:
          AttributeType.STRING,
      },

      billingMode:
        BillingMode.PAY_PER_REQUEST,

      pointInTimeRecoverySpecification: {
        pointInTimeRecoveryEnabled:
          true,
      },
    },
  );

/*
 * Per-user Checkout Session rate limit.
 *
 * The table is intentionally private and is not exposed through
 * Amplify Data / AppSync raw CRUD.
 *
 * One item exists per Cognito user that starts Checkout.
 */
const checkoutRateLimitTable =
  new Table(
    billingStack,
    "CheckoutRateLimitTable",
    {
      partitionKey: {
        name:
          "userId",

        type:
          AttributeType.STRING,
      },

      billingMode:
        BillingMode.PAY_PER_REQUEST,

      /*
       * Expired limiter records are only temporary operational data.
       * DynamoDB removes them asynchronously without consuming write
       * throughput.
       */
      timeToLiveAttribute:
        "expiresAt",
    },
  );
  
/*
 * Immutable server-side snapshot of one Checkout attempt.
 *
 * The table records the trusted billing contract and the
 * checkout-specific legal declarations that existed BEFORE the
 * Stripe Checkout Session was created.
 *
 * Browser clients never receive direct DynamoDB/AppSync CRUD access
 * to this table.
 */
const checkoutAttemptTable =
  new Table(
    billingStack,
    "CheckoutAttemptTable",
    {
      partitionKey: {
        name:
          "checkoutAttemptId",

        type:
          AttributeType.STRING,
      },

      billingMode:
        BillingMode.PAY_PER_REQUEST,

      pointInTimeRecoverySpecification: {
        pointInTimeRecoveryEnabled:
          true,
      },
    },
  );

