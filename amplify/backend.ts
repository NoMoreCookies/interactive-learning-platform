/*
 * Private customer complaint storage.
 *
 * Complaint records are not exposed as Amplify Data models.
 * Access is mediated exclusively by dedicated Lambda functions.
 *
 * The table is retained if its CloudFormation stack is removed,
 * protecting complaint history against accidental deletion.
 */
const complaintsStack =
  backend.createStack("complaints");

const complaintTable = new Table(
  complaintsStack,
  "ComplaintTable",
  {
    partitionKey: {
      name: "complaintId",
      type: AttributeType.STRING,
    },

    billingMode:
      BillingMode.PAY_PER_REQUEST,

    pointInTimeRecoverySpecification: {
      pointInTimeRecoveryEnabled: true,
    },

    removalPolicy:
      RemovalPolicy.RETAIN,
  },
);

/*
 * Customer complaint history.
 *
 * Access pattern:
 * userId -> complaints ordered by createdAt.
 */
complaintTable.addGlobalSecondaryIndex({
  indexName: "userId-createdAt-index",

  partitionKey: {
    name: "userId",
    type: AttributeType.STRING,
  },

  sortKey: {
    name: "createdAt",
    type: AttributeType.STRING,
  },

  projectionType:
    ProjectionType.KEYS_ONLY,
});

/*
 * Administrative complaint queue.
 *
 * Access pattern:
 * status -> complaints ordered by createdAt.
 */
complaintTable.addGlobalSecondaryIndex({
  indexName: "status-createdAt-index",

  partitionKey: {
    name: "status",
    type: AttributeType.STRING,
  },

  sortKey: {
    name: "createdAt",
    type: AttributeType.STRING,
  },

  projectionType:
    ProjectionType.KEYS_ONLY,
});

/*
 * Operational monitoring.
 *
 * CloudWatch alarms detect failures and capacity pressure.
 * All alarms publish to one SNS topic.
 *
 * Email subscriptions are intentionally configured outside IaC
 * so personal email addresses are not committed to the repository.
 */
const monitoringStack =
  backend.createStack(
    "monitoring",
  );

/*
 * Central notification channel for operational alerts.
 *
 * Do not hard-code a physical topic name here.
 * Sandbox and production can coexist in the same AWS account
 * and region, so CloudFormation should generate an
 * environment-specific physical name.
 */
const operationalAlertsTopic =
  new Topic(
    monitoringStack,
    "OperationalAlertsTopic",
    {
      displayName:
        "poprostumatma operational alerts",
    },
  );

const operationalAlertsAction =
  new SnsAction(
    operationalAlertsTopic,
  );

/*
 * Stripe webhook errors.
 *
 * Any unhandled Lambda error in the payment webhook is important:
 * it can delay processing of a successful Stripe payment.
 *
 * Expected invalid webhook requests should be handled by the
 * function and returned as normal HTTP responses rather than
 * unhandled Lambda exceptions.
 */
const stripeWebhookErrorsAlarm =
  new Alarm(
    monitoringStack,
    "StripeWebhookErrorsAlarm",
    {
      metric:
        backend
          .stripeWebhook
          .resources
          .lambda
          .metricErrors({
            period:
              Duration.minutes(
                5,
              ),

            statistic:
              "Sum",
          }),

      threshold: 1,

      evaluationPeriods: 1,

      datapointsToAlarm: 1,

      treatMissingData:
        TreatMissingData.NOT_BREACHING,

      alarmDescription:
        "Stripe webhook Lambda produced at least one unhandled error within 5 minutes.",
    },
  );

stripeWebhookErrorsAlarm
  .addAlarmAction(
    operationalAlertsAction,
  );

/*
 * Stripe webhook HTTP 5xx responses.
 *
 * The webhook intentionally returns HTTP 500 for processing failures so
 * Stripe retries them. A handled 500 response does not increment the Lambda
 * Errors metric, therefore API Gateway 5xx must be monitored separately.
 */
